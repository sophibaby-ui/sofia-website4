/** 依國曆流年數 sN 與農曆流年數 lN 組出綜合解讀（無農曆資料時回傳 null） */
export function buildYearMix(sN, lN) {
  if (!sN || !lN) return null;
  const grp = (n) => ([1, 5, 7].indexOf(n) >= 0 ? "a" : [2, 4, 8].indexOf(n) >= 0 ? "b" : "c");
  const rel = sN === lN ? "same" : grp(sN) === grp(lN) ? "flow" : "tension";
  return {
    rel,
    relLabel: rel === "same" ? "內外同步" : rel === "flow" ? "方向相近" : "內外拉扯",
    outer: PY_OUTER[sN] || "",
    inner: PY_INNER[lN] || "",
    summary: PY_MIX[rel] || "",
  };
}

/** 農曆流年數：以農曆生日的月日計算（僅取數字，期間仍以國曆為準） */
export function calcLunarYearNumber(lunarMonth, lunarDay, appliedYear) {
  const raw = sumDigits(appliedYear) + sumDigits(lunarMonth) + sumDigits(lunarDay);
  const final = reduceTo9(raw);
  return { raw, final, display: raw === final ? String(final) : raw + "／" + final };
}
