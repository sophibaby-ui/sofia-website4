const isLeap = (y) => (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
const sumDigits = (s) => String(s).split("").reduce((a, x) => a + (parseInt(x) || 0), 0);
const reduceTo9 = (n) => { while (n > 9) n = String(n).split("").reduce((a, x) => a + parseInt(x), 0); return n; };
const fmt = (d) => d.getFullYear() + "/" + (d.getMonth() + 1) + "/" + d.getDate();

/**
 * @param {number} bm 出生月
 * @param {number} bd 出生日
 * @param {Date}   today 查詢日（預設今天，時區沿用瀏覽器 / Asia/Taipei）
 */
export function calcPersonalYear(bm, bd, today = new Date()) {
  const y = today.getFullYear();
  // 2/29 出生者：非閏年以 2/28 為切換日
  const adjDay = (yr) => (bm === 2 && bd === 29 && !isLeap(yr) ? 28 : bd);

  const bdayThisYear = new Date(y, bm - 1, adjDay(y));
  const t = new Date(y, today.getMonth(), today.getDate());
  const applied = t >= bdayThisYear ? y : y - 1;

  const raw = sumDigits(applied) + sumDigits(bm) + sumDigits(bd);
  const final = reduceTo9(raw);

  const start = new Date(applied, bm - 1, adjDay(applied));
  const end = new Date(applied + 1, bm - 1, adjDay(applied + 1));
  end.setDate(end.getDate() - 1);

  return {
    applied,
    raw,
    final,
    display: raw === final ? String(final) : raw + "／" + final,
    periodStart: fmt(start),
    periodEnd: fmt(end),
    content: PERSONAL_YEAR[String(final)],
  };
}

